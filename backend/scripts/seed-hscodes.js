async function seedHsCodes(client = prisma) {
  await client.hsCode.deleteMany();
  const result = await client.hsCode.createMany({
    data: sampleHsCodes.map((item) => ({
      hsCode: item.hsCode,
      productName: item.productName,
      taxRate: item.taxRate,
      unit: item.unit,
      note: item.note,
      effectiveDate: new Date(item.effectiveDate),
    })),
  });

  return result.count;
}

