/** 临时 SQLite 合成数据：报关手工创建、明细编辑与失败回滚。 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
test('报关手工维护完整往返，保持明细ID及来源字段，失败原子回滚', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'jiesong-customs-test-'));
  fs.chmodSync(directory, 0o700);
  const dbFile = path.join(directory, 'synthetic.db');
  process.env.DATABASE_URL = `file:${dbFile}`;
  process.env.NODE_ENV = 'test';
  let db;
  t.after(async () => { if (db) await db.$disconnect(); fs.rmSync(directory, {recursive:true,force:true}); });
  const ddl = execFileSync(process.execPath, [require.resolve('prisma/build/index.js'), 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', path.resolve(__dirname, '../../prisma/schema.prisma'), '--script'], {encoding:'utf8',timeout:30000});
  execFileSync('python3',['-c','import sqlite3,sys,os; os.umask(0o077); c=sqlite3.connect(sys.argv[1]); c.executescript(sys.stdin.read()); c.close()', dbFile],{input:ddl});
  db = require('../utils/prisma');
  const service = require('../services/customsDeclarationService');
  const product = await db.product.create({data:{customsName:'合成商品'}});
  const sales = await db.salesContract.create({data:{contractNo:'SYNTHETIC',exchangeRate:7}});
  const packing = await db.packingItem.create({data:{salesContractId:sales.id,productId:product.id,quantity:2}});
  const rate = await db.taxRate.create({data:{productId:product.id,refundRate:13,effectiveFrom:new Date('2026-01-01')}});
  const input = {declarationNo:'SYNTHETIC-CUSTOMS',salesContractId:sales.id,declaredAt:'2026-10-01',exportDate:'2026-10-02',totalQuantity:2,items:[{productId:product.id,customsName:'合成申报品名',packingItemId:packing.id,taxRateId:rate.id,quantity:2,unitPrice:3,totalPrice:6,declarationElements:'合成要素',itemNo:1}]};
  const created = await service.createCustomsDeclaration(input);
  const read = await service.getCustomsDeclarationById(created.id);
  assert.equal(read.items.length,1);
  const item = {...input.items[0],id:read.items[0].id};
  const updated = await service.updateCustomsDeclaration(created.id,{...input,note:'修改',items:[{...item,quantity:3},{...input.items[0],itemNo:2}]});
  assert.equal(updated.items.length,2);
  assert.equal(updated.items[0].id,item.id);
  assert.equal(updated.items[0].declarationElements,'合成要素');
  assert.equal(updated.items[0].packingItemId,packing.id);assert.equal(updated.items[0].taxRateId,rate.id);
  await assert.rejects(service.updateCustomsDeclaration(created.id,{note:'不应保留',items:[{...item,productId:'missing-product'}]}));
  const after = await service.getCustomsDeclarationById(created.id);
  assert.equal(after.note,'修改');assert.equal(after.items.length,2);assert.equal(after.items[0].quantity,3);
  await assert.rejects(service.updateCustomsDeclaration(created.id,{items:[{...item,id:'foreign-line'}]}),e=>e.statusCode===400);
  await service.updateCustomsDeclaration(created.id,{items:[item]});
  assert.equal((await service.getCustomsDeclarationById(created.id)).items.length,1);
  await service.updateCustomsDeclaration(created.id,{note:'仅表头'});
  assert.equal((await service.getCustomsDeclarationById(created.id)).items[0].id,item.id);
});
